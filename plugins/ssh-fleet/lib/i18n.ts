/**
 * Every visible string of the plugin, in English and Russian. The panel picks
 * the language from the `language` setting (`auto`, `en`, `ru`); the server
 * keeps the current one in `setLanguage` so CLI output, refusals and stored
 * probe errors follow the same setting.
 *
 * Money: the data is in rubles. Russian shows "₽", English shows the ISO code
 * "RUB" after the amount; nothing is converted.
 */
export type Lang = "en" | "ru";
export type LanguageSetting = "auto" | "en" | "ru";

export const LANGUAGE_OPTIONS = ["auto", "en", "ru"] as const;

/** `auto`: Russian when any given locale (page, browser, system) starts with `ru`, English otherwise. */
export function resolveLanguage(setting: unknown, locales: ReadonlyArray<string | null | undefined>): Lang {
  if (setting === "en" || setting === "ru") return setting;
  return locales.some((locale) => typeof locale === "string" && locale.toLowerCase().startsWith("ru")) ? "ru" : "en";
}

/** Locales the server can see for `auto`: the process environment and Intl. */
export function systemLocales(): string[] {
  const env = typeof process === "undefined" ? {} : process.env;
  return [env.LC_ALL, env.LC_MESSAGES, env.LANG, Intl.DateTimeFormat().resolvedOptions().locale].filter(
    (value): value is string => typeof value === "string" && value !== "",
  );
}

