const STRINGS: Record<Lang, Record<Key, string>> = { en, ru };

export type MessageKey = Key;
export type Params = Record<string, string | number>;

export function translate(lang: Lang, key: Key, params?: Params): string {
  const text = STRINGS[lang][key];
  if (params === undefined) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}

let current: Lang = "en";

export function setLanguage(lang: Lang): void {
  current = lang;
}

export function getLanguage(): Lang {
  return current;
}

/** Server-side lookup in the current language. */
export function t(key: Key, params?: Params): string {
  return translate(current, key, params);
}

export function locale(lang: Lang): string {
  return lang === "ru" ? "ru-RU" : "en-US";
}

/** "1 сервер / 2 сервера / 5 серверов", "1 server / 2 servers". */
export function serversCount(lang: Lang, count: number): string {
  if (lang === "en") return `${count} ${count === 1 ? "server" : "servers"}`;
  const mod10 = count % 10;
  const mod100 = count % 100;
  const word =
    mod10 === 1 && mod100 !== 11
      ? "сервер"
      : mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)
        ? "сервера"
        : "серверов";
  return `${count} ${word}`;
}
